// Append-only: the app role has no UPDATE or DELETE on this table.
export const punchEvent = pgTable(
  "punch_event",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    businessId: uuid("business_id")
      .notNull()
      .references(() => business.id, { onDelete: "cascade" }),
    cardId: uuid("card_id")
      .notNull()
      .references(() => card.id, { onDelete: "cascade" }),
    locationId: uuid("location_id").references(() => location.id, { onDelete: "set null" }),
    staffUserId: text("staff_user_id").references(() => user.id, { onDelete: "set null" }),
    deviceId: uuid("device_id").references(() => device.id, { onDelete: "set null" }),
    // +n for a punch, -n for an undo.
    delta: integer("delta").notNull(),
    reason: text("reason"),
    // Set by the staff app so offline-queued punches are not applied twice.
    clientEventId: uuid("client_event_id").unique(),
    createdAt: createdAt(),
  },
  (t) => [
    index("punch_event_business_created_idx").on(t.businessId, t.createdAt),
    index("punch_event_card_id_idx").on(t.cardId),
    check("punch_event_delta_nonzero", sql`${t.delta} <> 0`),
  ],
);

